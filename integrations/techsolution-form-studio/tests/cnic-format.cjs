const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = { module: { exports: {} } };
vm.runInNewContext(fs.readFileSync(__dirname + '/../public/assets/js/tsfs-cnic.js', 'utf8'), context);
const format = context.module.exports;
assert.equal(format('1234512345671'), '12345-1234567-1');
assert.equal(format('12345-1234567-1'), '12345-1234567-1');
assert.equal(format('12345678901234'), '12345678901234');
assert.equal(format('123456'), '12345-6');
assert.equal(format(''), '');
console.log('Passed CNIC formatting, partial entry, and no-truncation checks.');
